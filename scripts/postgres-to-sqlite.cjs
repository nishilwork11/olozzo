#!/usr/bin/env node
/*
 * Moves olozzo's data from the old Postgres (Neon) database into the SQLite database.
 * The Postgres database is only ever READ. The SQLite target is DATABASE_URL (must be a file: URL).
 *
 *   node scripts/postgres-to-sqlite.cjs prepare          generate the Postgres reader (run once after npm ci)
 *   node scripts/postgres-to-sqlite.cjs backup <dir>     dump every Postgres table to <dir>/<Model>.json
 *   node scripts/postgres-to-sqlite.cjs copy [--replace] copy all rows into the SQLite database, then verify
 *   node scripts/postgres-to-sqlite.cjs verify           compare both databases table by table
 *
 * Environment: SOURCE_DATABASE_URL = the Postgres connection string (Neon "DATABASE_URL_UNPOOLED");
 *              DATABASE_URL        = the SQLite file, e.g. file:/var/lib/olozzo/olozzo.db
 * The SQLite tables must exist first: npx prisma db push
 * `copy` refuses to write into a database that already has rows unless --replace is given; --replace first
 * saves a snapshot of the current SQLite file next to it, then empties it and copies everything again.
 */
const { execSync } = require("child_process");
const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const PG_DIR = path.join(ROOT, "prisma", "postgres");
const PG_CLIENT = path.join(PG_DIR, "client");
const CHUNK = 100;

const [, , command, ...rest] = process.argv;
const flags = new Set(rest.filter((a) => a.startsWith("--")));
const args = rest.filter((a) => !a.startsWith("--"));

function die(message) {
  console.error(`\n✖ ${message}`);
  process.exit(1);
}

// ── Prisma clients ──────────────────────────────────────────

function prepare() {
  const schema = fs.readFileSync(path.join(ROOT, "prisma", "schema.prisma"), "utf8");
  const pgSchema = schema
    .replace(/generator client \{[^}]*\}/, 'generator client {\n  provider = "prisma-client-js"\n  output   = "./client"\n}')
    .replace(/datasource db \{[^}]*\}/, 'datasource db {\n  provider = "postgresql"\n  url      = env("SOURCE_DATABASE_URL")\n}');
  fs.mkdirSync(PG_DIR, { recursive: true });
  fs.writeFileSync(path.join(PG_DIR, "schema.prisma"), "// Generated by scripts/postgres-to-sqlite.cjs prepare — do not edit\n" + pgSchema);
  execSync(`npx prisma generate --schema "${path.join(PG_DIR, "schema.prisma")}"`, { cwd: ROOT, stdio: "inherit" });
  console.log("\n✔ Postgres reader generated in prisma/postgres/client");
}

function source() {
  const url = process.env.SOURCE_DATABASE_URL || "";
  if (!/^postgres(ql)?:\/\//.test(url)) die("SOURCE_DATABASE_URL must be the Postgres connection string (postgresql://…).");
  if (!fs.existsSync(path.join(PG_CLIENT, "index.js"))) die("Run `node scripts/postgres-to-sqlite.cjs prepare` first.");
  const { PrismaClient } = require(PG_CLIENT);
  console.log(`Source (read only): Postgres at ${new URL(url).hostname}`);
  return new PrismaClient();
}

function sqliteFile() {
  const url = process.env.DATABASE_URL || "";
  if (!url.startsWith("file:")) die('DATABASE_URL must be the SQLite file, e.g. DATABASE_URL="file:/var/lib/olozzo/olozzo.db".');
  const file = url.slice("file:".length).split("?")[0];
  return path.isAbsolute(file) || /^[A-Za-z]:[\\/]/.test(file) ? file : path.resolve(ROOT, "prisma", file);
}

function target() {
  const file = sqliteFile();
  if (!fs.existsSync(file)) die(`${file} does not exist yet. Create the tables first: npx prisma db push`);
  const { PrismaClient } = require("@prisma/client");
  console.log(`Target: SQLite file ${file}`);
  return new PrismaClient();
}

// ── Models in foreign-key order ─────────────────────────────

function models() {
  const { Prisma } = require("@prisma/client");
  const all = Prisma.dmmf.datamodel.models.map((m) => ({
    name: m.name,
    delegate: m.name[0].toLowerCase() + m.name.slice(1),
    scalars: m.fields.filter((f) => f.kind === "scalar" || f.kind === "enum").map((f) => f.name),
    // foreign keys pointing at another model (must be inserted first) and at the same model (inserted in passes)
    deps: [...new Set(m.fields.filter((f) => f.kind === "object" && f.relationFromFields?.length && f.type !== m.name).map((f) => f.type))],
    selfKeys: m.fields.filter((f) => f.kind === "object" && f.relationFromFields?.length && f.type === m.name).flatMap((f) => f.relationFromFields),
  }));
  const ordered = [];
  const done = new Set();
  while (ordered.length < all.length) {
    const next = all.find((m) => !done.has(m.name) && m.deps.every((d) => done.has(d)));
    if (!next) die("Circular foreign keys between models: " + all.filter((m) => !done.has(m.name)).map((m) => m.name).join(", "));
    ordered.push(next);
    done.add(next.name);
  }
  return ordered;
}

// ── Helpers ─────────────────────────────────────────────────

const plain = (v) => (v instanceof Date ? v.toISOString() : v);
const stable = (row, fields) => JSON.stringify(fields.map((f) => [f, plain(row[f] ?? null)]));

async function readAll(client, model) {
  return client[model.delegate].findMany({ orderBy: { id: "asc" } });
}

function digest(rows, fields) {
  const lines = rows.map((r) => stable(r, fields)).sort();
  return crypto.createHash("sha256").update(lines.join("\n")).digest("hex").slice(0, 16);
}

// Rows of a self-referencing model (Category → parent) go in after the rows they point at
function inDependencyOrder(rows, selfKeys) {
  if (!selfKeys.length) return [rows];
  const passes = [];
  const placed = new Set();
  let left = rows;
  while (left.length) {
    const ready = left.filter((r) => selfKeys.every((k) => r[k] == null || placed.has(r[k])));
    if (!ready.length) die("Rows point at missing parents: " + left.slice(0, 5).map((r) => r.id).join(", "));
    ready.forEach((r) => placed.add(r.id));
    passes.push(ready);
    left = left.filter((r) => !placed.has(r.id));
  }
  return passes;
}

// ── Commands ────────────────────────────────────────────────

async function backup(dir) {
  if (!dir) die("Usage: backup <folder>");
  const src = source();
  const out = path.resolve(dir);
  fs.mkdirSync(out, { recursive: true });
  const manifest = { createdAt: new Date().toISOString(), source: new URL(process.env.SOURCE_DATABASE_URL).hostname, tables: {} };
  for (const m of models()) {
    const rows = await readAll(src, m);
    fs.writeFileSync(path.join(out, `${m.name}.json`), JSON.stringify(rows, null, 1));
    manifest.tables[m.name] = { rows: rows.length, sha256: digest(rows, m.scalars) };
    console.log(`  ${m.name.padEnd(16)} ${String(rows.length).padStart(6)} rows`);
  }
  fs.copyFileSync(path.join(ROOT, "prisma", "schema.prisma"), path.join(out, "schema.prisma"));
  fs.writeFileSync(path.join(out, "manifest.json"), JSON.stringify(manifest, null, 2));
  await src.$disconnect();
  console.log(`\n✔ Backup written to ${out} (contains password hashes and customer data — keep it private)`);
}

async function counts(client, list) {
  const result = {};
  for (const m of list) result[m.name] = await client[m.delegate].count();
  return result;
}

async function copy() {
  const list = models();
  const dst = target();
  const src = source();

  const existing = await counts(dst, list);
  const nonEmpty = Object.entries(existing).filter(([, n]) => n > 0);
  if (nonEmpty.length) {
    if (!flags.has("--replace")) die(`The SQLite database already has data (${nonEmpty.map(([t, n]) => `${t}: ${n}`).join(", ")}). Use --replace to save a snapshot of it and copy everything again.`);
    // olozzo.db → olozzo.before-replace-<time>.db (keeps the .db ending, so .gitignore covers local copies)
    const snapshot = sqliteFile().replace(/(\.db)?$/, `.before-replace-${new Date().toISOString().replace(/[:.]/g, "-")}.db`);
    await dst.$executeRawUnsafe(`VACUUM INTO '${snapshot.replace(/'/g, "''")}'`);
    console.log(`Snapshot of the current SQLite data: ${snapshot}`);
    for (const m of [...list].reverse()) {
      if (m.selfKeys.length) await dst[m.delegate].updateMany({ data: Object.fromEntries(m.selfKeys.map((k) => [k, null])) });
      await dst[m.delegate].deleteMany();
    }
  }

  for (const m of list) {
    const rows = await readAll(src, m);
    const data = rows.map((r) => Object.fromEntries(m.scalars.filter((f) => r[f] !== undefined).map((f) => [f, r[f]])));
    for (const pass of inDependencyOrder(data, m.selfKeys)) {
      for (let i = 0; i < pass.length; i += CHUNK) await dst[m.delegate].createMany({ data: pass.slice(i, i + CHUNK) });
    }
    console.log(`  ${m.name.padEnd(16)} ${String(rows.length).padStart(6)} rows copied`);
  }

  // WAL lets visitors keep reading while an order is being written; it is stored in the file itself
  await dst.$queryRawUnsafe("PRAGMA journal_mode = WAL;");
  const broken = await dst.$queryRawUnsafe("PRAGMA foreign_key_check;");
  if (broken.length) die(`Foreign key problems after copying: ${JSON.stringify(broken.slice(0, 5))}`);

  const ok = await compare(src, dst, list);
  await Promise.all([src.$disconnect(), dst.$disconnect()]);
  if (!ok) die("The copy does not match the source (see above).");
  console.log("\n✔ All data copied and verified: every table matches Postgres row for row.");
}

async function compare(src, dst, list) {
  let ok = true;
  console.log(`\n  ${"table".padEnd(16)} ${"postgres".padStart(9)} ${"sqlite".padStart(9)}  result`);
  for (const m of list) {
    const [a, b] = await Promise.all([readAll(src, m), readAll(dst, m)]);
    const same = a.length === b.length && digest(a, m.scalars) === digest(b, m.scalars);
    if (!same) ok = false;
    console.log(`  ${m.name.padEnd(16)} ${String(a.length).padStart(9)} ${String(b.length).padStart(9)}  ${same ? "match" : "DIFFERENT"}`);
    if (!same) {
      const ids = new Set(b.map((r) => r.id));
      const missing = a.filter((r) => !ids.has(r.id)).map((r) => r.id);
      if (missing.length) console.log(`      only in Postgres (e.g. new since the copy): ${missing.slice(0, 10).join(", ")}${missing.length > 10 ? " …" : ""}`);
    }
  }
  return ok;
}

async function verify() {
  const list = models();
  const dst = target();
  const src = source();
  const ok = await compare(src, dst, list);
  await Promise.all([src.$disconnect(), dst.$disconnect()]);
  if (!ok) die("The databases differ. Run `copy --replace` again to take a fresh copy.");
  console.log("\n✔ Postgres and SQLite contain exactly the same data.");
}

(async () => {
  switch (command) {
    case "prepare": return prepare();
    case "backup": return backup(args[0]);
    case "copy": return copy();
    case "verify": return verify();
    default: die("Usage: node scripts/postgres-to-sqlite.cjs prepare | backup <dir> | copy [--replace] | verify");
  }
})().catch((e) => die(String(e && e.stack ? e.stack : e).slice(0, 1500)));
